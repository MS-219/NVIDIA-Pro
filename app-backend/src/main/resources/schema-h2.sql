CREATE TABLE IF NOT EXISTS app_admin_audit_log (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, admin_username VARCHAR(80) NOT NULL, action VARCHAR(80) NOT NULL, resource_type VARCHAR(40) NOT NULL, resource_id VARCHAR(80), detail CLOB, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
